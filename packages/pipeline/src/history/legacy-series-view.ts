import type { LegacySeriesExperimentPerson, LegacySeriesResult } from './legacy-series-types';
import { createSourceExportPolicy } from '../export/source-export-policy';

/** Read-only projection; retains the historical versions and recorded scores. */
export function legacySeriesView(result: LegacySeriesResult): LegacySeriesResult {
  const policy = createSourceExportPolicy([...result.people, result.control]);
  const participant = (value: LegacySeriesExperimentPerson): LegacySeriesExperimentPerson => ({
    ...value,
    profile: policy.profile(value.profile),
    baseProfile: policy.profile(value.baseProfile),
    report: policy.report(value.report),
    // Historical artifact text is preserved and receives the same snippet filter.
    // It is never regenerated by today's persona renderer.
  });
  const people = result.people.map(participant);
  const control = participant(result.control);
  const body = policy.serialize({
    ...result,
    people,
    control,
    traces: policy.traces(result.traces),
  });
  // This is our own validated domain snapshot with filtered arrays/strings only;
  // the external kebab-case decoder does not apply to this internal view.
  return JSON.parse(body) as LegacySeriesResult;
}
